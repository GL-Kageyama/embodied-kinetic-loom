"""電線——**機体ごとの、数え方と、バイト列。**

⛔ **このモジュールは、機体の名前を1つも書かない。**
ここに在るのは**境界の形**であって、境界の向こう側ではない。

⚠️ **なぜ要るのか。** このリポジトリは機体依存の部分を `protocol.py` の中に直書きしていた——
5バイトの `[A xx]` フレーム、`A`/`B`/`C` の3モーター、0〜1024 の2バイト表現。
**2台目の機体はこのどれも共有しない。**
⇒ **そのまま2本目を書けば、共通の1行が2箇所に書かれる**——
`tools/purity.py` が「一覧を2つ書くと、片方だけが直る」と書いているのと同じ形の欠陥である。

**だから、この層が持つのは「軸」と「値」だけである。**
軸は**モーターの番号**であって、自由度の名前ではない——
**名前を知っているのは `AxisMap` だけである**（`engine/backend/axis_map.py`）。

⛔ **そして `decode` を、この Protocol に入れていない。**
機体1の読み側の形は**2つの出典で食い違っており**、`protocol.py` は
**意図的に `decode_feedback` を書いていない**（同モジュールの docstring を見よ）。
**実装できないメソッドを必須にすることは、嘘を1つ置くことである。**
読み側は、機械の前で決まる。

⚠️ **`Envelope` は、この Protocol に無い。**
枠は「この機体がどこまで動けるか」という**測定**であると同時に、
**「今回はどこまで動かすか」という判断**でもある——
**初めて触る日に、わざと狭くしたいことはある。**
⇒ **枠は `Gate` と `Rig` の必須引数であり、電線はそれを持たない。**
"""
from __future__ import annotations

from dataclasses import dataclass
from typing import Protocol, Sequence

__all__ = ["Command", "Wire"]


@dataclass(frozen=True)
class Command:
    """**機体へ向かう1つの指示。** 軸と、その機体の数え方での値だけを持つ。

    ⛔ **生のバイト列を、ここに持たせない。**
    1モーター1フレームの機体では「1つの指示＝1つのバイト列」で済むが、
    **1行に2軸を運ぶ機体では、その等式が成り立たない**——
    **片方の軸だけのバイト列というものが、存在しないのである。**
    ⇒ **バイト列にするのは `Wire.encode` の仕事であり、それは組ごとに1回だけ走る。**

    ⚠️ **`axis` はモーターの番号である。** 自由度の名前ではない——
    名前からモーターへの対応は `AxisMap` が持ち、**この型は知らない。**
    """

    axis: int
    value: float


