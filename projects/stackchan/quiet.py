# -*- coding: utf-8 -*-
"""**静かな時間。** 21:00–05:00 は、音を出さない。

⛔ **このファイルは時計を読まない。** 時刻は縁が読み、**時という数を値として**ここへ来る
（`behaviors.py` と同じ形である）。⇒ **同じ時を渡せば、同じ答えが返る。**

## なぜ、コードに書くのか

⚠️ **規則は記憶に在った。** 「21:00–05:00 は静かに」は著者の規則であり、
**それまでは `--sound off` という1つの旗で守られていた**——**音そのものを切ることで。**
⇒ **夜を守る唯一の方法が、昼も鳴らさないことだった。**
⛔ **時刻がコードに無いあいだ、音は「暮らせる」に届かない。**

## 境界

| 時 | 音 |
|---|---|
| 20 | 出してよい |
| **21** | **静か（ここから）** |
| 0–4 | 静か |
| **5** | **出してよい（ここまで）** |

⚠️ **分は持たない。** 規則の両端はどちらも正時であり、
**分を受け取ることは、無い精度を作ることである。**
⛔ **端の時は静かな側である**——21:00 は静か、05:00 は昼。
"""
from __future__ import annotations

#: ⚠️ **著者の規則（2026-10-19）の数は、ここに1つだけ在る。**
QUIET_FROM = 21
QUIET_UNTIL = 5


def is_quiet(hour: int) -> bool:
    """**その時は静かか。** 0–23 のほかは `ValueError` である。

    ⛔ **黙って別の答えを返さない。** 24 や -1 は時ではなく、
    **時を読んだ側の誤りであり、ここで名指す。**
    """
    if not isinstance(hour, int) or isinstance(hour, bool):
        raise TypeError(hour)
    if hour < 0 or hour > 23:
        raise ValueError(hour)
    return hour >= QUIET_FROM or hour < QUIET_UNTIL


__all__ = ["QUIET_FROM", "QUIET_UNTIL", "is_quiet"]
